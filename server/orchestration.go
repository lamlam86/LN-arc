// deriveTaskStatus mirrors listTasks' status derivation for the list_tasks tool.
func (s *Server) deriveTaskStatus(t *Task) string {
	lifecycle := t.lifecycleSnapshot()
	switch {
	case isTerminalStatus(lifecycle.Status):
		return lifecycle.Status
	case lifecycle.Paused || s.engine.IsPaused(t.ID):
		return "paused"
	case s.engine.ReadyFor(t) && s.engine.Started(t.ID):
		return "running"
	}
	return "created"
}

// orchestrationToolSeeds seeds the cross-task tools into the tools table so they
// are bindable per-agent (default: bound to nobody — opt-in for orchestration
// agents). First-insert only, like the traffic seeds.
func (s *Server) seedOrchestrationTools() {
	// Task-operation and platform tools default-bind to built-in Auto, whose purpose is
	// platform operation. SeedTool inserts only; seedAutoDefaultBindings updates existing rows.
	autoAgents, _ := json.Marshal([]string{"auto"})
	for _, t := range s.orchestrationTools() {
		schema, _ := json.Marshal(t.InputSchema())
		_ = s.m.PG().SeedTool(t.Name(), t.Description(), schema, autoAgents)
	}
	for _, t := range s.platformTools() {
		schema, _ := json.Marshal(t.InputSchema())
		_ = s.m.PG().SeedTool(t.Name(), t.Description(), schema, autoAgents)
	}
	s.refreshBuiltinToolSchemas()
	s.seedAutoDefaultBindings()
	s.seedPlannerListAssetsBinding()
	s.seedCompanyScopeRebind()
	s.seedWorkerReadToolsUnbind() // One-time default unbinding of list_facts/list_companies/list_worker_traces from worker.
	s.seedWorkerReadbackRebind()  // Repair earlier migration: rebind search_all_worker_traces/get_worker_trace/node_detail to worker.
	s.unbindGoalMetDefault()
	s.reseedGoalsPrompt()     // One-time goals prompt version adding extraction of operation constraints.
	s.reseedMainAgentPrompt() // One-time mainagent prompt addition: ask whether to create goals for post-completion add_intent.
	s.reseedPlannerPrompt()   // One-time planner prompt rewrite: valid zero-intent cases and quantitative acceptance checks.
	s.reseedWorkerPrompt()    // One-time worker prompt addition: evidence threshold for negative conclusions.
	// pentest default tool bindings need no migration: fresh BuiltinToolSeeds inserts
	// list_assets/insert_assets/list_companies with pentest; no older databases
	// existed when this was added.
}

// refreshBuiltinToolSchemas propagates code schema/description changes on the
// orchestration + platform tools into already-seeded rows ONCE per version flag —
// SeedTool is first-insert-only, so a new param (e.g. spawn_task llm_profile) never
// reaches an old DB otherwise. Preserves each tool's agent binding + enabled flag.
// Bump the flag whenever these tools' schemas/descriptions change in code.
func (s *Server) refreshBuiltinToolSchemas() {
	const flag = "tool_schema_refresh_v7_list_facts_paging"
	if v, _, _ := s.m.pg.GetSetting(flag); v == "true" {
		return
	}
	tools := append(s.orchestrationTools(), s.platformTools()...)
	for _, t := range tools {
		schema, _ := json.Marshal(t.InputSchema())
		if err := s.m.pg.RefreshToolDefaults(t.Name(), t.Description(), schema); err != nil {
			log.Printf("[tools] refresh %s schema failed: %v", t.Name(), err)
		}
	}
	// Also refresh selected built-in tools to code defaults:
	// goal_met: an old description misleadingly said to end the planning round,
	// causing the planner to end an empty round by incorrectly completing the whole task.
	// insert_assets: new related argument marks task relevance and coverage inclusion;
	// first-insert-only seeding would leave existing schemas without this argument.
	// list_facts: pagination adds limit/before/q; old empty schemas otherwise display
	// no parameters in tool management and provide no argument guidance to the model.
	refreshBuiltin := map[string]bool{"goal_met": true, "insert_assets": true, "list_facts": true}
	for _, sd := range agent.BuiltinToolSeeds() {
		if !refreshBuiltin[sd.Key] {
			continue
		}
		schema, _ := json.Marshal(sd.Schema)
		if err := s.m.pg.RefreshToolDefaults(sd.Key, sd.Desc, schema); err != nil {
			log.Printf("[tools] refresh %s desc failed: %v", sd.Key, err)
		}
	}
	_ = s.m.pg.SetSetting(flag, "true")
	log.Printf("[tools] Refreshed orchestration/platform tool schemas to code defaults (one-time)")
}

// unbindGoalMetDefault removes goal_met's default "planner" binding ONCE (guarded by
// a settings flag), so existing DBs match the new default of NO agent. goal_met bypasses
// per-goal prove_goal to declare the whole task done — powerful/risky and redundant with
// the prove_goal→auto-complete path — so it ships unbound; users can re-bind it per agent
// in the UI. A user's own binding to another agent is untouched (we only strip planner).
func (s *Server) unbindGoalMetDefault() {
	const flag = "goal_met_unbind_default_v1"
	if v, _, _ := s.m.pg.GetSetting(flag); v == "true" {
		return
	}
	if err := s.m.pg.RemoveAgentFromTool("planner", "goal_met"); err != nil {
		log.Printf("[tools] Failed to unbind goal_met from planner: %v", err)
		return
	}
	_ = s.m.pg.SetSetting(flag, "true")
}

// reseedGoalsPrompt appends the current default as a new version, adding
// extraction of constraints (set_constraints) before goal decomposition.
// SeedPromptIfEmpty only inserts, so ResetPromptToDefault appends and activates a version.
// Old versions remain recoverable, including user customizations. A settings flag runs this once;
// bump it for later default changes. Fresh databases already receive the latest default.
func (s *Server) reseedGoalsPrompt() {
	const flag = "goals_prompt_constraint_step_v1"
	if v, _, _ := s.m.pg.GetSetting(flag); v == "true" {
		return
	}
	defer func() { _ = s.m.pg.SetSetting(flag, "true") }() // Attempt once regardless of success.
	a, err := s.m.pg.GetAgentByKey("goals")
	if err != nil || a == nil {
		return // Fresh databases without the agent row are handled by seedPrompts.
	}
	tmpl := agent.BuiltinPromptSeeds()["goals"]
	if tmpl == "" {
		return
	}
	// Fresh seedPrompts already used the current default; do not append a duplicate version.
	if cur, err := s.m.pg.CurrentPrompt(a.ID); err == nil && cur == tmpl {
		return
	}
	if _, err := s.m.pg.ResetPromptToDefault(a.ID, tmpl); err != nil {
		log.Printf("[prompts] Failed to reset goals prompt to new default: %v", err)
		return
	}
	log.Printf("[prompts] Appended new goals default prompt version (extract operation constraints, one-time)")
}

